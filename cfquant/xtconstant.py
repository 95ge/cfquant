_UPSTREAM_XTCONSTANT = None
_UPSTREAM_XTCONSTANT_LOADED = False


def _upstream_xtconstant_module():
    global _UPSTREAM_XTCONSTANT
    global _UPSTREAM_XTCONSTANT_LOADED
    if _UPSTREAM_XTCONSTANT_LOADED:
        return _UPSTREAM_XTCONSTANT
    _UPSTREAM_XTCONSTANT_LOADED = True
    try:
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            _UPSTREAM_XTCONSTANT = importlib.import_module("xtquant.xtconstant")
    except Exception:
        _UPSTREAM_XTCONSTANT = None
    return _UPSTREAM_XTCONSTANT


def _load_upstream_xtquant_constants():
    module = _upstream_xtconstant_module()
    if module is None:
        return
    for name in dir(module):
        if not name.isupper() or name.startswith("_") or name in globals():
            continue
        try:
            globals()[name] = getattr(module, name)
        except Exception:
            pass


def __getattr__(name):
    if name.isupper() and not name.startswith("_"):
        module = _upstream_xtconstant_module()
        if module is not None and hasattr(module, name):
            value = getattr(module, name)
            globals()[name] = value
            return value
    raise AttributeError("module %r has no attribute %r" % (__name__, name))

__all__ = sorted(name for name in globals() if name.isupper() and not name.startswith("_"))
